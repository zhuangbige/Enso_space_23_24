def _set_run_font(
    run,
    *,
    size: float | None = None,
    bold: bool | None = None,
    italic: bool | None = None,
    color: str = BLACK,
) -> None:
    run.font.name = BODY_FONT
    run._element.get_or_add_rPr()
    fonts = run._element.rPr.get_or_add_rFonts()
    fonts.set(qn("w:ascii"), BODY_FONT)
    fonts.set(qn("w:hAnsi"), BODY_FONT)
    fonts.set(qn("w:eastAsia"), EAST_ASIA_FONT)
    fonts.set(qn("w:cs"), BODY_FONT)
    if size is not None:
        run.font.size = Pt(size)
    if bold is not None:
        run.bold = bold
    if italic is not None:
        run.italic = italic
    run.font.color.rgb = RGBColor.from_string(color)


def _set_style_font(style, *, size: float, bold: bool, color: str) -> None:
    style.font.name = BODY_FONT
    style.font.size = Pt(size)
    style.font.bold = bold
    style.font.color.rgb = RGBColor.from_string(color)
    rpr = style._element.get_or_add_rPr()
    fonts = rpr.get_or_add_rFonts()
    fonts.set(qn("w:ascii"), BODY_FONT)
    fonts.set(qn("w:hAnsi"), BODY_FONT)
    fonts.set(qn("w:eastAsia"), EAST_ASIA_FONT)
    fonts.set(qn("w:cs"), BODY_FONT)


def configure_document(doc: Document) -> None:
    section = doc.sections[0]
    section.page_width = Inches(8.5)
    section.page_height = Inches(11)
    section.top_margin = Inches(1)
    section.bottom_margin = Inches(1)
    section.left_margin = Inches(1)
    section.right_margin = Inches(1)
    section.header_distance = Inches(0.492)
    section.footer_distance = Inches(0.492)

    normal = doc.styles["Normal"]
    _set_style_font(normal, size=11, bold=False, color=BLACK)
    normal.paragraph_format.space_before = Pt(0)
    normal.paragraph_format.space_after = Pt(8)
    normal.paragraph_format.line_spacing = 1.333
    normal.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY

    for name, size, color, before, after in (
        ("Heading 1", 16, BLUE, 18, 10),
        ("Heading 2", 13, BLUE, 12, 6),
        ("Heading 3", 12, DARK_BLUE, 8, 4),
    ):
        style = doc.styles[name]
        _set_style_font(style, size=size, bold=True, color=color)
        style.paragraph_format.space_before = Pt(before)
        style.paragraph_format.space_after = Pt(after)
        style.paragraph_format.line_spacing = 1.0
        style.paragraph_format.keep_with_next = True

    caption = doc.styles["Caption"]
    _set_style_font(caption, size=9, bold=False, color=MUTED)
    caption.font.italic = True
    caption.paragraph_format.space_before = Pt(2)
    caption.paragraph_format.space_after = Pt(8)
    caption.paragraph_format.line_spacing = 1.0
    caption.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.CENTER
    _set_header_footer(section)


def _add_page_field(paragraph) -> None:
    run = paragraph.add_run()
    begin = OxmlElement("w:fldChar")
    begin.set(qn("w:fldCharType"), "begin")
    instruction = OxmlElement("w:instrText")
    instruction.set(qn("xml:space"), "preserve")
    instruction.text = " PAGE "
    separate = OxmlElement("w:fldChar")
    separate.set(qn("w:fldCharType"), "separate")
    text = OxmlElement("w:t")
    text.text = "1"
    end = OxmlElement("w:fldChar")
    end.set(qn("w:fldCharType"), "end")
    run._r.extend([begin, instruction, separate, text, end])
    _set_run_font(run, size=8.5, color=MUTED)


def _set_header_footer(section) -> None:
    header = section.header
    paragraph = header.paragraphs[0]
    paragraph.alignment = WD_ALIGN_PARAGRAPH.LEFT
    paragraph.paragraph_format.space_after = Pt(0)
    run = paragraph.add_run("2023/24 ENSO AIR-SEA COUPLING | MINIMAL CLOSURE")
    _set_run_font(run, size=8.5, bold=True, color=MUTED)
    footer = section.footer
    p = footer.paragraphs[0]
    p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    p.paragraph_format.space_before = Pt(0)
    prefix = p.add_run("Page ")
    _set_run_font(prefix, size=8.5, color=MUTED)
    _add_page_field(p)


def add_heading(doc: Document, text: str, level: int = 1) -> None:
    paragraph = doc.add_paragraph(style=f"Heading {level}")
    paragraph.paragraph_format.keep_with_next = True
    run = paragraph.add_run(text)
    _set_run_font(
        run,
        size={1: 16, 2: 13, 3: 12}[level],
        bold=True,
        color={1: BLUE, 2: BLUE, 3: DARK_BLUE}[level],
    )


def add_body(doc: Document, text: str, *, bold_lead: str | None = None) -> None:
    paragraph = doc.add_paragraph()
    if bold_lead and text.startswith(bold_lead):
        lead = paragraph.add_run(bold_lead)
        _set_run_font(lead, size=11, bold=True)
        rest = paragraph.add_run(text[len(bold_lead) :])
        _set_run_font(rest, size=11)
    else:
        run = paragraph.add_run(text)
        _set_run_font(run, size=11)


def add_callout(doc: Document, label: str, text: str) -> None:
    table = doc.add_table(rows=1, cols=1)
    table.rows[0]._tr.get_or_add_trPr().append(OxmlElement("w:tblHeader"))
    _set_table_geometry(table, [9360])
    cell = table.cell(0, 0)
    _set_cell_shading(cell, LIGHT_FILL)
    _set_cell_margins(cell, top=160, bottom=160, start=180, end=180)
    paragraph = cell.paragraphs[0]
    paragraph.paragraph_format.space_after = Pt(2)
    label_run = paragraph.add_run(label + "  ")
    _set_run_font(label_run, size=10.5, bold=True, color=DARK_BLUE)
    text_run = paragraph.add_run(text)
    _set_run_font(text_run, size=10.5)
    spacer = doc.add_paragraph()
    spacer.paragraph_format.space_after = Pt(2)


def _set_cell_shading(cell, fill: str) -> None:
    tc_pr = cell._tc.get_or_add_tcPr()
    shd = tc_pr.find(qn("w:shd"))
    if shd is None:
        shd = OxmlElement("w:shd")
        tc_pr.append(shd)
    shd.set(qn("w:fill"), fill)


def _set_cell_margins(cell, *, top: int = 80, bottom: int = 80, start: int = 120, end: int = 120) -> None:
    tc_pr = cell._tc.get_or_add_tcPr()
    tc_mar = tc_pr.first_child_found_in("w:tcMar")
    if tc_mar is None:
        tc_mar = OxmlElement("w:tcMar")
        tc_pr.append(tc_mar)
    for name, value in (("top", top), ("bottom", bottom), ("start", start), ("end", end)):
        node = tc_mar.find(qn(f"w:{name}"))
        if node is None:
            node = OxmlElement(f"w:{name}")
            tc_mar.append(node)
        node.set(qn("w:w"), str(value))
        node.set(qn("w:type"), "dxa")


def _set_table_geometry(table, widths: list[int], indent: int = 120) -> None:
    if sum(widths) != 9360:
        raise ValueError(f"table widths must sum to 9360 DXA: {widths}")
    table.autofit = False
    tbl_pr = table._tbl.tblPr
    tbl_w = tbl_pr.find(qn("w:tblW"))
    if tbl_w is None:
        tbl_w = OxmlElement("w:tblW")
        tbl_pr.append(tbl_w)
    tbl_w.set(qn("w:w"), "9360")
    tbl_w.set(qn("w:type"), "dxa")
    tbl_ind = tbl_pr.find(qn("w:tblInd"))
    if tbl_ind is None:
        tbl_ind = OxmlElement("w:tblInd")
        tbl_pr.append(tbl_ind)
    tbl_ind.set(qn("w:w"), str(indent))
    tbl_ind.set(qn("w:type"), "dxa")

    grid = table._tbl.tblGrid
    for child in list(grid):
        grid.remove(child)
    for width in widths:
        column = OxmlElement("w:gridCol")
        column.set(qn("w:w"), str(width))
        grid.append(column)
    for row in table.rows:
        for cell, width in zip(row.cells, widths):
            tc_pr = cell._tc.get_or_add_tcPr()
            tc_w = tc_pr.find(qn("w:tcW"))
            if tc_w is None:
                tc_w = OxmlElement("w:tcW")
                tc_pr.append(tc_w)
            tc_w.set(qn("w:w"), str(width))
            tc_w.set(qn("w:type"), "dxa")
            cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
            _set_cell_margins(cell)


def add_data_table(
    doc: Document,
    headers: list[str],
    rows: list[list[str]],
    widths: list[int],
    *,
    font_size: float = 9,
) -> None:
    table = doc.add_table(rows=1, cols=len(headers))
    table.style = "Table Grid"
    for cell, value in zip(table.rows[0].cells, headers):
        cell.text = value
        _set_cell_shading(cell, MID_FILL)
    for row in rows:
        cells = table.add_row().cells
        for cell, value in zip(cells, row):
            cell.text = str(value)
            _set_cell_shading(cell, WHITE)
    _set_table_geometry(table, widths)
    table.rows[0]._tr.get_or_add_trPr().append(OxmlElement("w:tblHeader"))
    for row_index, row in enumerate(table.rows):
        row_properties = row._tr.get_or_add_trPr()
        cant_split = OxmlElement("w:cantSplit")
        row_properties.append(cant_split)
        for cell_index, cell in enumerate(row.cells):
            for paragraph in cell.paragraphs:
                paragraph.paragraph_format.space_before = Pt(0)
                paragraph.paragraph_format.space_after = Pt(0)
                paragraph.paragraph_format.line_spacing = 1.05
                paragraph.alignment = (
                    WD_ALIGN_PARAGRAPH.LEFT if cell_index == 0 else WD_ALIGN_PARAGRAPH.CENTER
                )
                for run in paragraph.runs:
                    _set_run_font(run, size=font_size, bold=(row_index == 0))
    spacer = doc.add_paragraph()
    spacer.paragraph_format.space_after = Pt(2)


def add_figure(doc: Document, path: Path, caption: str, *, width: float = 6.35) -> None:
    if not path.exists():
        raise FileNotFoundError(path)
    paragraph = doc.add_paragraph()
    paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
    paragraph.paragraph_format.space_after = Pt(2)
    paragraph.paragraph_format.keep_with_next = True
    inline_shape = paragraph.add_run().add_picture(str(path), width=Inches(width))
    doc_pr = inline_shape._inline.docPr
    doc_pr.set("descr", caption)
    cap = doc.add_paragraph(style="Caption")
    cap.paragraph_format.keep_with_next = False
    run = cap.add_run(caption)
    _set_run_font(run, size=9, italic=True, color=MUTED)


def add_hyperlink(paragraph, text: str, url: str) -> None:
    part = paragraph.part
    relation_id = part.relate_to(
        url,
        "http://schemas.openxmlformats.org/officeDocument/2006/relationships/hyperlink",
        is_external=True,
    )
    hyperlink = OxmlElement("w:hyperlink")
    hyperlink.set(qn("r:id"), relation_id)
    run = OxmlElement("w:r")
    properties = OxmlElement("w:rPr")
    color = OxmlElement("w:color")
    color.set(qn("w:val"), BLUE)
    underline = OxmlElement("w:u")
    underline.set(qn("w:val"), "single")
    properties.extend([color, underline])
    run.append(properties)
    node = OxmlElement("w:t")
    node.text = text
    run.append(node)
    hyperlink.append(run)
    paragraph._p.append(hyperlink)


def _result_language(scores: pd.DataFrame) -> tuple[str, pd.DataFrame]:
    target = scores[
        (scores["event"] == "2023/24")
        & (scores["product_combo"] == "OISST+ERA5")
        & (scores["status"] == "complete_event")
    ].copy()
    target = target.sort_values(["historical_percentile", "eta"])
    minimum_percentile = float(target["historical_percentile"].min())
    lowest_history = target[np.isclose(target["historical_percentile"], minimum_percentile)]
    weakest_eta = target.loc[target["eta"].idxmin()]
    significant = target[target["significantly_weakened"].astype(str).str.lower().isin(["true", "1"])]
    if significant.empty:
        low_names = "、".join(LINK_LABELS_CN[str(link)] for link in lowest_history["link"])
        history_phrase = (
            f"{low_names} 的历史相对位置并列最低（第 {minimum_percentile:.1f} 百分位）"
            if len(lowest_history) > 1
            else f"{low_names} 的历史相对位置最低（第 {minimum_percentile:.1f} 百分位）"
        )
        text = (
            f"四条链中，{history_phrase}；"
            f"{LINK_LABELS_CN[str(weakest_eta['link'])]} 的实现率最低（eta={weakest_eta['eta']:.2f}）。"
            "但没有链条同时满足“低于历史第5百分位”"
            "和“bootstrap 95%置信区间上限低于1”两个条件。因此核心结论应表述为异常排序，而不是宣称统计显著的反馈崩塌。"
        )
    else:
        names = "、".join(LINK_LABELS_CN[str(link)] for link in significant["link"])
        text = f"按预注册的双重判据，2023/24 显著减弱的反馈环节为：{names}。"
    return text, target


def _product_stability(sensitivity: pd.DataFrame) -> tuple[str, list[list[str]]]:
    target = sensitivity[sensitivity["event"] == "2023/24"].copy()
    rows = []
    weakest = []
    for product, group in target.groupby("product_combo", sort=False):
        ordered = group.sort_values("eta")
        weakest.append(str(ordered.iloc[0]["link"]))
        rows.append(
            [
                product,
                LINK_LABELS_CN[str(ordered.iloc[0]["link"])],
                f"{ordered.iloc[0]['eta']:.2f}",
                f"{LINK_LABELS_CN[str(ordered.iloc[-1]['link'])]} ({ordered.iloc[-1]['eta']:.2f})",
            ]
        )
    stable = len(set(weakest)) == 1
    sentence = (
        "三套产品组合给出的最低 eta 环节一致，主结论的方向对 SST/风应力产品选择稳定。"
        if stable
        else "不同产品组合给出的最低 eta 环节不完全一致，因此最终归因标记为资料依赖。"
    )
    return sentence, rows


